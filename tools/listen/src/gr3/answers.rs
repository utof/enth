//! Answers, from the owner's session file and from the friends' `answers.txt`, in one shape; and the kit's text files.
//!
//! The owner's answers are `AnswerFile`s (`answers.json`, saved after every answer, the same schema family as the
//! other tools). A friend's `answers.txt` is plain text that any editor can fill:
//!
//! ```text
//! # enth GR3 listening kit
//! kit: kit1
//! # ... instructions ...
//! 01: a
//! 02: b
//! 03:
//! ```
//!
//! A line is a trial number, a separator (`:`, `=`, `-` or a space) and `a` or `b`; an empty answer is a skipped
//! trial. `#` starts a comment. Nothing else is accepted: a typo is reported with its line number, not guessed at.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::design::{Manifest, Trial};
use crate::Res;
use crate::session::AnswerFile;

/// One listener's answers, keyed by the trial's number in their sequence.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Responses {
    /// Who (the owner, or the friend's file name without extension).
    pub listener: String,
    /// `owner` or `kit<N>`.
    pub audience: String,
    /// Generated by `--dry-run`.
    pub synthetic: bool,
    /// Trial number to `a` or `b`.
    pub choices: BTreeMap<usize, char>,
}

/// The owner's answers file as responses.
///
/// # Errors
/// An answer for a trial the key does not have, or one that is neither `a` nor `b`.
pub fn owner_responses(m: &Manifest, f: &AnswerFile) -> Res<Responses> {
    let trials = m.trials_of(super::design::OWNER);
    let mut choices = BTreeMap::new();
    for a in &f.answers {
        let t = trials.iter().find(|t| t.id == a.id).ok_or_else(|| {
            format!(
                "the owner's answers hold trial {:?}, which the key does not have",
                a.id
            )
        })?;
        let c = match a.choice.as_str() {
            "a" => 'a',
            "b" => 'b',
            other => {
                return Err(
                    format!("trial {:?}: answer {other:?} is neither a nor b", a.id).into(),
                );
            }
        };
        choices.insert(t.n, c);
    }
    Ok(Responses {
        listener: super::design::OWNER.into(),
        audience: super::design::OWNER.into(),
        synthetic: f.synthetic,
        choices,
    })
}

/// Parse a friend's `answers.txt`.
///
/// # Errors
/// A message with the line number: no `kit:` line, an unknown trial number, a number twice, or anything but a number and
/// `a` or `b`.
pub fn parse_kit_answers(listener: &str, text: &str, m: &Manifest) -> Res<Responses> {
    let mut kit: Option<String> = None;
    let mut synthetic = false;
    let mut choices = BTreeMap::new();
    for (i, raw) in text.lines().enumerate() {
        let at = i + 1;
        let line = raw.trim().trim_start_matches('\u{feff}');
        if let Some(c) = line.strip_prefix('#') {
            synthetic |= c.trim_start().starts_with("SYNTHETIC");
            continue;
        }
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let lower = line.to_lowercase();
        if let Some(name) = lower
            .strip_prefix("kit")
            .and_then(|r| r.trim_start().strip_prefix(':'))
        {
            kit = Some(name.trim().to_string());
            continue;
        }
        let digits = line.chars().take_while(char::is_ascii_digit).count();
        let (num, rest) = line.split_at(digits);
        let rest = rest
            .trim_start_matches([':', '=', '-', ' ', '\t', '.'])
            .trim()
            .to_lowercase();
        let n: usize = num.parse().map_err(|_| {
            format!(
                "{listener}, line {at}: expected a trial number, a colon and a or b, found {line:?}"
            )
        })?;
        let c = match rest.as_str() {
            "" => None,
            "a" => Some('a'),
            "b" => Some('b'),
            _ => {
                return Err(format!(
                    "{listener}, line {at}: the answer for trial {n} must be a or b, found {rest:?}"
                )
                .into());
            }
        };
        if choices.insert(n, c).is_some() {
            return Err(format!("{listener}, line {at}: trial {n} appears twice").into());
        }
    }
    let kit = kit.ok_or_else(|| {
        format!("{listener}: no `kit: kitN` line; answers.txt must keep the header it came with")
    })?;
    let trials = m.trials_of(&kit);
    if trials.is_empty() {
        return Err(format!("{listener}: the key has no kit {kit:?}").into());
    }
    let mut out = BTreeMap::new();
    for (n, c) in choices {
        if !trials.iter().any(|t| t.n == n) {
            return Err(format!(
                "{listener}: trial {n} does not exist in {kit} (it has {})",
                trials.len()
            )
            .into());
        }
        if let Some(c) = c {
            out.insert(n, c);
        }
    }
    Ok(Responses {
        listener: listener.into(),
        audience: kit,
        synthetic,
        choices: out,
    })
}

/// A kit's `answers.txt`: the instructions and one empty line per trial. With `filled` it carries those answers (the
/// dry run), and a `SYNTHETIC` line.
#[must_use]
pub fn kit_answers_text(
    kit: &str,
    trials: &[&Trial],
    filled: Option<&BTreeMap<usize, char>>,
) -> String {
    let mut s = String::new();
    s.push_str("# enth GR3 listening kit\n");
    let _ = writeln!(s, "kit: {kit}");
    if filled.is_some() {
        s.push_str("# SYNTHETIC answers written by --dry-run; nobody listened\n");
    }
    s.push_str(
        "# For each numbered trial, play its three files in order: file 1 is the reference, file 2 is sound A,\n\
         # file 3 is sound B. Decide which of A and B sounds closer to the reference, and type a or b after the colon.\n\
         # Leave a line empty to skip a trial. Keep the numbers and the kit line as they are.\n\
         # Save the file and send it back. Do not look for which file is which: there is nothing to find, the names are random.\n",
    );
    for t in trials {
        let a = filled
            .and_then(|f| f.get(&t.n))
            .map(|c| format!(" {c}"))
            .unwrap_or_default();
        let _ = writeln!(s, "{:02}:{a}", t.n);
    }
    s
}

/// A kit's `README.txt`.
#[must_use]
pub fn kit_readme(kit: &str, trials: &[&Trial]) -> String {
    let seconds: f64 = trials
        .iter()
        .map(|t| t.seconds.iter().sum::<f64>() * 1.2 + 7.0)
        .sum();
    format!(
        "enth listening test ({kit}): {n} short trials, about {min:.0} minutes\n\
         \n\
         What this is: for each trial you hear a reference sound, then sound A, then sound B. A and B are two\n\
         attempts to copy the reference. You say which one is closer to the reference. There is no right or wrong\n\
         taste here: pick the one that is closer to the reference, and go with your first impression.\n\
         \n\
         How:\n\
         1. Use headphones. Set the volume once, to a comfortable level, and do not touch it again: every file is\n\
         \x20  level-matched, so the loudness is the same everywhere.\n\
         2. The files are named NN-K-xxxxxx.wav. NN is the trial number. K is 1 for the reference, 2 for sound A,\n\
         \x20  3 for sound B, so sorting by name puts them in playing order. Any player on any system will do.\n\
         3. For trial 01, play the three files in that order (you may replay them as often as you like), then open\n\
         \x20  answers.txt and type a or b after \"01:\". Continue with 02, 03, ...\n\
         4. Some trials are checks (two identical sounds, or one sound that is clearly wrong): just answer them like\n\
         \x20  the others.\n\
         5. You can stop at any time and continue later. Send answers.txt back when you are done.\n\
         \n\
         Please do not share the files or discuss the sounds with anyone before everyone has sent their answers.\n",
        n = trials.len(),
        min = seconds / 60.0
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::gr3::design::{DEFAULT_SEED, design};
    use crate::gr3::dry::demo_set;
    use crate::gr3::set::Set;
    use crate::session::Answer;

    fn key(name: &str) -> (std::path::PathBuf, Manifest) {
        let d = std::env::temp_dir().join(format!(
            "enth-listen-gr3answers-{name}-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&d);
        let set = Set::load(&demo_set(&d, 12).unwrap()).unwrap();
        let m = design(&set, DEFAULT_SEED, 2, &d.join("out")).unwrap();
        (d, m)
    }

    #[test]
    fn the_template_round_trips_through_the_parser() {
        let (d, m) = key("template");
        let trials = m.trials_of("kit2");
        let empty = kit_answers_text("kit2", &trials, None);
        let r = parse_kit_answers("friend", &empty, &m).unwrap();
        assert_eq!(
            (r.audience.as_str(), r.choices.len(), r.synthetic),
            ("kit2", 0, false)
        );
        let filled: BTreeMap<usize, char> = trials
            .iter()
            .map(|t| (t.n, if t.n % 2 == 0 { 'a' } else { 'b' }))
            .collect();
        let text = kit_answers_text("kit2", &trials, Some(&filled));
        let r = parse_kit_answers("friend", &text, &m).unwrap();
        assert_eq!(r.choices, filled);
        assert!(r.synthetic);
        assert!(kit_readme("kit2", &trials).contains("NN-K-xxxxxx.wav"));
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn friends_may_type_loosely_but_not_wrongly() {
        let (d, m) = key("loose");
        let ok = "\u{feff}# Enth GR3 listening kit\nKIT: kit1\n01: A   # first\n2 = b\n3 - \n4. a\n 05 :B\n";
        let r = parse_kit_answers("f", ok, &m).unwrap();
        assert_eq!(
            r.choices.into_iter().collect::<Vec<_>>(),
            vec![(1, 'a'), (2, 'b'), (4, 'a'), (5, 'b')]
        );
        let bad = |body: &str| {
            parse_kit_answers("f", &format!("kit: kit1\n{body}"), &m)
                .unwrap_err()
                .to_string()
        };
        assert!(bad("01: c\n").contains("line 2") && bad("01: c\n").contains("a or b"));
        assert!(bad("01: a\n01: b\n").contains("twice"));
        assert!(bad("99: a\n").contains("does not exist"));
        assert!(bad("hello\n").contains("expected a trial number"));
        assert!(
            parse_kit_answers("f", "01: a\n", &m)
                .unwrap_err()
                .to_string()
                .contains("kit")
        );
        assert!(
            parse_kit_answers("f", "kit: kit9\n01: a\n", &m)
                .unwrap_err()
                .to_string()
                .contains("kit9")
        );
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn owner_answers_map_to_trial_numbers() {
        let (d, m) = key("owner");
        let trials = m.trials_of("owner");
        let mut f = AnswerFile::new("enth.listen.gr3-answers/1", 1, false);
        f.answers.push(Answer {
            n: 1,
            id: trials[3].id.clone(),
            choice: "b".into(),
            replays: 0,
            ms: 1,
        });
        let r = owner_responses(&m, &f).unwrap();
        assert_eq!(r.choices.get(&trials[3].n), Some(&'b'));
        f.answers.push(Answer {
            n: 2,
            id: "nope".into(),
            choice: "a".into(),
            replays: 0,
            ms: 1,
        });
        assert!(owner_responses(&m, &f).is_err());
        std::fs::remove_dir_all(&d).unwrap();
    }
}
